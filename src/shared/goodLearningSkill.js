/** 精简版：无科目上下文时只注入方法论骨架，节省 token */
const SKILL_DIGEST = `# 学习与备考方法论（Good Learning 精简版）

- 有考试日期 → 备考模式（围绕日期倒推、优先考点）；无 → 学习模式（系统掌握、间隔复习）。
- 知识清单与计划分离：清单按可检查的知识点拆分（编号、条件、题型、前置、优先级、状态、验收）；计划按天排任务并引用编号。
- 缺学习基础或可用时间信息时，先问再规划，不臆造。
- 每日课程：讲清概念与条件 → 完整例题（分步+理由）→ 填步题 → 独立变式 → 混合题，答案后置；零基础少而精。
- 用户只要知识点总结时，只输出该知识点本身，不套用每日课程结构，不附加拓展、延伸阅读、学习建议或鼓励语。
- 错题必记：出处、错步、有证据的错因、完整订正、复做题与日期；未验证的保持「待验证」。
- 写进 Obsidian 的笔记：数学公式一律用 LaTeX（$...$ 行内、$$...$$ 块级），中文说明留在公式外，不要写 Unicode 伪公式或 \\(...\\) 旧定界符。`;

/**
 * 组装科目上下文：把 skill + 科目现状 + 资料分层拼成 system 的一段。
 * @param {object|null} subject  科目记录
 * @param {object} opts  { digestOnly, materials, materialContext }
 *   materials       —— 资料清单摘要（主教材/补充资料元信息）
 *   materialContext —— 按当前问题检索出的带来源原文片段（主教材优先）
 */
function buildSubjectSkillBlock(subject, opts = {}) {
  const skill = opts.digestOnly ? SKILL_DIGEST : SKILL_TEXT;
  if (!subject) {
    return `\n\n## 学习与备考方法论\n\n${skill}\n\n当前对话没有绑定科目。用户想系统学某个科目时，建议他先到「科目」页创建科目（可设置考试日期与上传教材），这样你能基于教材和清单工作。`;
  }

  const lines = [`\n\n## 当前科目：${subject.name}`];
  const examDate = subject.examDate || subject.exam_date || null;
  if ((subject.mode === 'exam' || (examDate && !subject.mode)) && examDate) {
    const days = Math.ceil((new Date(`${examDate}T00:00:00`) - new Date(new Date().toDateString())) / 86400000);
    lines.push(`模式：备考模式（考试日期 ${examDate}，还有 ${days} 天）。一切安排围绕倒计时展开，优先考试范围与高频考点。`);
  } else {
    lines.push('模式：学习模式（无考试日期）。以系统掌握为目标，按教材顺序推进，安排间隔复习。');
  }
  const textbookStatus = subject.textbookStatus || subject.textbook_status || 'none';
  lines.push(`教材状态：${textbookStatus === 'ready' ? '已解析完成，教材全文在科目文件夹，知识清单已生成' : textbookStatus === 'parsing' ? '解析中' : '未上传教材（工作只能基于对话与用户提供的内容）'}`);

  const profile = subject.profile && typeof subject.profile === 'object' ? subject.profile : null;
  if (profile && (profile.level || profile.dailyHours)) {
    lines.push(`学习基础：${profile.level || '未填写'}；每天可用：${profile.dailyHours || '?'} 小时，每周 ${profile.weeklyDays || '?'} 天${profile.style ? `；偏好：${profile.style}` : ''}${profile.notes ? `；备注：${profile.notes}` : ''}`);
  } else if (textbookStatus === 'ready') {
    lines.push('【重要】该科目的教材已解析完成，但你还不知道用户的学习基础和可用时间。请主动、简短地询问（学过什么、自评水平、每天能学几小时、每周几天），拿到答复后用 update_subject_profile 存档，再用 write_notes 生成该科目的学习计划。不要跳过询问直接编计划。');
  }

  const knowledgeSummary = subject.knowledgeSummary || subject.knowledge_summary || '';
  if (knowledgeSummary) {
    // 完整清单正文：不再截前 1200 字，否则模型看不到后几章，改清单时只能重复前几章
    lines.push(`知识清单（完整正文，修改时保持未涉及章节不变）：\n${String(knowledgeSummary)}`);
  }

  // 资料分层：主教材优先、补充资料辅助（AnythingLLM pinned document 的本地化实现）
  if (opts.materials) lines.push(String(opts.materials));

  lines.push(`\n## Good Learning 方法论（用于知识清单 / 学习计划 / 每日学习 / 整科教学；用户只要知识点总结时不要套用其中的每日学习结构）\n\n${skill}`);

  // 检索出的原文片段放在最后：模型对靠近结尾的「当前任务材料」注意力更稳，
  // 且方法论段落不会被大段原文挤掉。
  if (opts.materialContext) lines.push(`\n## 本次可参考的资料原文\n\n${String(opts.materialContext)}`);
  return lines.join('\n\n');
}

module.exports = {
  GOOD_LEARNING_SKILL: SKILL_TEXT,
  SKILL_DIGEST,
  buildSubjectSkillBlock,
};
